/**
 * Generates `src/lib/i18n/keys.ts`, the `MessageKey` type, from the Fluent files, so `t()`
 * calls are checked against the English source at compile time.
 *
 *   bun run i18n:keys          write the file
 *   bun run i18n:keys check    fail if the file is out of date
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { FluentResource } from "@fluent/bundle";
import { PROJECT_ROOT } from "./extension-build.js";

export const LOCALES_DIR = join(PROJECT_ROOT, "src", "locales");
export const KEYS_FILE = join(PROJECT_ROOT, "src", "lib", "i18n", "keys.ts");

/** Interslavic-only messages standing in for Intl formatting that has no `isv` CLDR data. */
export const CLDR_GAP_PREFIX = "cldr-";

export function readLocale(code: string): string {
  return readFileSync(join(LOCALES_DIR, code, "feedtubes.ftl"), "utf8");
}

/** Message ids of a Fluent file, in file order (terms, starting with `-`, excluded). */
export function messageIds(source: string): string[] {
  return new FluentResource(source).body
    .map((message) => message.id)
    .filter((id) => !id.startsWith("-"));
}

function union(ids: readonly string[]): string {
  return ids.map((id) => `\n  | "${id}"`).join("");
}

export function renderKeysModule(): string {
  const english = messageIds(readLocale("eng"));
  const gaps = messageIds(readLocale("isv-Latn")).filter((id) => id.startsWith(CLDR_GAP_PREFIX));
  return [
    "// Generated by `bun run i18n:keys` from src/locales/. Do not edit.",
    "",
    "/** Ids of the messages in `src/locales/eng/feedtubes.ftl`. */",
    `export type MessageKey =${union(english)};`,
    "",
    "/** Interslavic-only formatting messages (`isv-Latn`), used where CLDR has no data. */",
    `export type CldrGapKey =${union(gaps)};`,
    "",
  ].join("\n");
}

if (import.meta.main) {
  const expected = renderKeysModule();
  if (process.argv[2] === "check") {
    let current = "";
    try {
      current = readFileSync(KEYS_FILE, "utf8");
    } catch {
      // Missing counts as out of date.
    }
    if (current.replaceAll("\r\n", "\n") !== expected) {
      console.error("src/lib/i18n/keys.ts is out of date. Run `bun run i18n:keys`.");
      process.exit(1);
    }
  } else {
    writeFileSync(KEYS_FILE, expected);
    console.log("Wrote src/lib/i18n/keys.ts");
  }
}
